-- Derive research-only empty-category targets from the freshly compiled DB.
local LL={}
assert(loadfile('LootLiquidator/ItemDBRuntime.lua'))('LootLiquidator',LL)
local covered={}
local function scan(records)
    for _,record in ipairs(records or {})do
        if record.method=='Disenchant' and type(record.gearKey)=='string' then covered[record.gearKey]=true end
    end
end
scan(LL.ItemDB.processing);scan(LL.ItemDB.legacy and LL.ItemDB.legacy.processing)
local expansions={[0]='Classic','The Burning Crusade','Wrath of the Lich King','Cataclysm',
    'Mists of Pandaria','Warlords of Draenor','Legion','Battle for Azeroth','Shadowlands',
    'Dragonflight','The War Within','Midnight'}
local qualities={[2]='Uncommon (green)',[3]='Rare (blue)',[4]='Epic (purple)'}
local lines={'-- Generated by tools/disenchant_research_gaps.lua; research-only, no invented rates.',
    "return {schemaVersion='loot-liquidator.disenchant-gaps/1',generatedForBuild='12.1.x',",
    "evidenceNeeded='Exact material identities, quantity units, operation counts when known, source profile, date, patch and source link.',",
    'targets={'}
local count=0
for era=0,11 do for quality=2,4 do for _,kind in ipairs({'armor','weapon'})do
    local key=('gear:%d:%d:%s'):format(era,quality,kind)
    if not covered[key] then
        local other=('gear:%d:%d:%s'):format(era,quality,kind=='armor' and 'weapon' or 'armor')
        local hasOther=covered[other]==true
        lines[#lines+1]=('{key=%q,expansionID=%d,expansion=%q,quality=%d,qualityName=%q,gearKind=%q,status="needs-data",variesByItemLevel=%s,otherKindHasData=%s,priority=%d},')
            :format(key,era,expansions[era],quality,qualities[quality],kind,
                era<=1 and 'true' or 'nil',hasOther and 'true' or 'nil',
                hasOther and 1 or (era>=7 and 2 or (era>=2 and 3 or 4)))
        count=count+1
    end
end end end
lines[#lines+1]='}}'
local text=table.concat(lines,'\n')..'\n'
local path=arg[1] or 'database/research/disenchant-gaps.lua'
if arg[2]=='--check' then
    local file=assert(io.open(path,'rb'));local current=file:read('*a');file:close()
    assert(current==text,'Disenchant research gap targets are stale; run tools/disenchant_research_gaps.lua')
else
    local file=assert(io.open(path,'wb'));file:write(text);file:close()
end
print('DISENCHANT RESEARCH GAPS: '..count..' empty categories; no rates or samples added')
