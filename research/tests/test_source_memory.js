"use strict";
const assert=require("node:assert/strict");const {normalize,build,applyCorrections}=require("../tools/build_source_memory");
const original={observationID:"one",studyID:"test-study",source:{url:"https://example.org/study?utm_source=x"},processing:{inputItemID:1,method:"Prospect"},outputs:[{outputItemID:2}]};
assert.equal(normalize("HTTPS://EXAMPLE.ORG/study/?utm_source=copy#comments"),"https://example.org/study");
let r=build([original],[],[]);
assert.equal(r.sourcesCount,1);assert.equal(r.sources[0].status,"DISCOVERED");
const ev={workerID:"midnight",sourceUrl:"https://example.org/study",status:"PARTIAL",reviewedAt:"2026-10-28",missingFields:["sample cast count"],recordKeys:["1:Prospect:2"]};
r=build([original],[ev],[]);
assert.equal(r.sourcesCount,1);assert.equal(r.sources[0].status,"PARTIAL");
assert.deepEqual(r.sources[0].missingFields,["sample cast count"]);
r=build([original],[ev,{...ev,status:"FULLY_ANALYZED",reviewedAt:"2026-10-29",missingFields:[]}],[]);
assert.equal(r.sources[0].status,"FULLY_ANALYZED");
const qa={qaOutcome:"ACCEPTED_NEW_EVIDENCE",strategyID:"REDDIT_PLAYER_STUDY",claimID:"claim-1",workerID:"midnight",reviewer:"master",reviewedAt:"2026-10-28"};
r=build([original],[ev],[qa,qa,{...qa,claimID:"claim-2",qaOutcome:"REJECTED_DUPLICATE"}]);
assert.equal(r.strategies.REDDIT_PLAYER_STUDY.points,3);
assert.equal(r.qaEvents,2);
assert.ok(r.warnings.some(x=>x.includes("repeat feedback")));
r=build([original],[{...ev,status:"UNSUPPORTED"}],[qa]);
assert.ok(r.warnings.some(x=>x.includes("invalid review")));
assert.equal(r.sources[0].status,"DISCOVERED");
const primer={observationID:"df-b008-fish-3-casts-wowhead-comment-primer",source:{url:"https://www.wowhead.com/item=200061/prismatic-leaper"},processing:{inputItemID:200061,method:"Mill"},outputs:[{outputItemID:198419}]};
const correction={corrections:[{correctionID:"primer-serene-r2-20261028-b016",status:"MASTER_QA_APPROVED",sourceUrl:primer.source.url,observationID:primer.observationID,incorrectRecordKey:"200061:Mill:198419",correctedRecordKey:"200061:Mill:198413",retainAsUnverifiedPossibleMapping:true}]};
let corrected=applyCorrections(build([primer],[],[]),correction);
assert.deepEqual(corrected.sources[0].reviewedRecordKeys,["200061:Mill:198413"]);
assert.deepEqual(corrected.sources[0].unverifiedPossibleMappings,["200061:Mill:198419"]);
assert.equal(corrected.appliedAttributionCorrectionIDs.length,1);
corrected=applyCorrections(corrected,correction);
assert.equal(corrected.sources[0].attributionCorrections.length,1,"idempotent replay");
assert.throws(()=>applyCorrections(build([primer],[],[]),{corrections:[{...correction.corrections[0],observationID:"wrong"}]}),/not found/);
const descriptive=build([{observationID:"almar",source:{url:"https://almarsguides.com/wow/farming/wotlk/otherlocations/Prospecting/",originalDocumentRef:"page section My Prospecting Titanium Video"}}],[],[]);
assert.ok(descriptive.sources[0].canonicalUrl.startsWith("https://almarsguides.com/"),"descriptive originalDocumentRef must not become a fake URL");
console.log("source memory tests passed: URL normalization, archive import, partial/full, feedback deduplication and invalid event guard");
